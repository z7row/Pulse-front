"use client";

import { useState } from "react";
import { markdownToHtml } from "@/lib/markdown";

interface MarkdownEditorProps {
  value: string;
  onChange: (v: string) => void;
  placeholder?: string;
  minHeight?: string; // e.g. "400px"
}

export default function MarkdownEditor({
  value,
  onChange,
  placeholder = "Write your story in Markdown…",
  minHeight = "420px",
}: MarkdownEditorProps) {
  const [tab, setTab] = useState<"write" | "preview">("write");

  return (
    <div className="rounded-xl border border-border overflow-hidden">
      <div className="flex items-center gap-1 border-b border-border bg-secondary/40 px-2">
        <TabButton active={tab === "write"} onClick={() => setTab("write")}>
          Write
        </TabButton>
        <TabButton active={tab === "preview"} onClick={() => setTab("preview")}>
          Preview
        </TabButton>
        <span className="ml-auto text-[11px] text-muted-foreground pr-2">
          Markdown supported — **bold**, *italic*, # heading, - list, &gt; quote
        </span>
      </div>

      {tab === "write" ? (
        <textarea
          value={value}
          onChange={(e) => onChange(e.target.value)}
          placeholder={placeholder}
          style={{ minHeight }}
          className="w-full p-4 bg-background text-foreground text-sm leading-relaxed font-mono focus:outline-none resize-y"
        />
      ) : (
        <div
          style={{ minHeight }}
          className="prose-preview p-4 text-sm text-foreground leading-relaxed"
          // Preview-only, generated by our own tiny converter above — not
          // rendering arbitrary third-party HTML.
          dangerouslySetInnerHTML={{ __html: markdownToHtml(value) }}
        />
      )}
    </div>
  );
}

function TabButton({
  active,
  onClick,
  children,
}: {
  active: boolean;
  onClick: () => void;
  children: React.ReactNode;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      className={`h-10 px-4 text-sm border-b-2 transition-colors ${
        active
          ? "border-accent text-foreground font-medium"
          : "border-transparent text-muted-foreground hover:text-foreground"
      }`}
    >
      {children}
    </button>
  );
}
